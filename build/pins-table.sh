#!/bin/bash
# The overview of the pins: sources.lock (versions, commits) joined with
# pins.notes (what each product is built from and how it is tested, and for
# every pin that is not a plain upstream release its base, change and test):
#
#   build/pins-table.sh [product ...]     the tables in Markdown, for release notes
#   build/pins-table.sh --readme <file>   rewrites the tables between the markers
#   build/pins-table.sh --check <file>    fails if the file's tables are not current
#
# It also fails when the two files disagree: a pin that no product uses, a
# commit pin without a change line, a name that sources.lock does not have.
set -euo pipefail

KIT=$(cd "$(dirname "$0")/.." && pwd)
BEGIN='<!-- pins: generated by build/pins-table.sh from sources.lock and pins.notes -->'
END='<!-- pins: end -->'

tables() {
    awk -v want="$*" '
    function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
    # the commit, linked when the repository is on GitHub
    function commit(name,   url) {
        url = URL[name]; sub(/^git\+/, "", url); sub(/\.git$/, "", url)
        if (url ~ /^https:\/\/github\.com\//)
            return "[`" substr(SHA[name], 1, 9) "`](" url "/commit/" SHA[name] ")"
        return "`" substr(SHA[name], 1, 9) "`"
    }
    # the version, and the commit of a git pin (alone when the version is that commit)
    function pin(name) {
        if (URL[name] !~ /^git\+/) return VER[name]
        return (index(SHA[name], VER[name]) == 1 ? "" : VER[name] " ") commit(name)
    }
    FNR == 1 { file++ }
    file == 1 && !/^[ \t]*(#|$)/ { VER[$1] = $2; URL[$1] = $3; SHA[$1] = $4; LOCK[++nlock] = $1; next }
    file == 2 && /^(product|change) / {
        kind = $1; sub(/^(product|change)[ \t]+/, "")
        n = split($0, f, "|"); for (i = 1; i <= n; i++) f[i] = trim(f[i])
        if (kind == "product") {
            P[++np] = f[1]; PNAME[f[1]] = f[2]; PSRC[f[1]] = f[3]; PTEST[f[1]] = f[4]
            m = split(f[3], s, " ")
            for (i = 1; i <= m; i++) {
                if (!(s[i] in VER)) { print "pins.notes: product " f[1] " uses " s[i] ", not in sources.lock" > "/dev/stderr"; bad = 1 }
                USED[s[i]] = 1
            }
        } else {
            if (!(f[1] in VER)) { print "pins.notes: change " f[1] " is not in sources.lock" > "/dev/stderr"; bad = 1 }
            CH[f[1]] = 1; CBASE[f[1]] = f[2]; CWHAT[f[1]] = f[3]; CTEST[f[1]] = f[4]
        }
    }
    END {
        for (i = 1; i <= nlock; i++) {
            name = LOCK[i]
            if (!(name in USED)) { print "pins.notes: no product uses " name > "/dev/stderr"; bad = 1 }
            if (URL[name] ~ /^git\+/ && !(name in CH)) { print "pins.notes: " name " is a commit pin without a change line" > "/dev/stderr"; bad = 1 }
        }
        if (bad) exit 1
        nw = split(want, w, " ")
        for (i = 1; i <= nw; i++) if (!(w[i] in PNAME)) { print "pins-table.sh: no product " w[i] > "/dev/stderr"; exit 1 }
        if (nw == 0) for (i = 1; i <= np; i++) w[++nw] = P[i]

        print "| Product | Built from (`sources.lock`) | Tested by |"
        print "|---|---|---|"
        for (i = 1; i <= nw; i++) {
            m = split(PSRC[w[i]], s, " "); list = ""
            for (j = 1; j <= m; j++) { list = list (j > 1 ? ", " : "") s[j] " " VER[s[j]]; SEL[s[j]] = 1 }
            print "| " PNAME[w[i]] " | " list " | " PTEST[w[i]] " |"
        }
        print ""
        print "Pins that are not a plain upstream release:"
        print ""
        print "| Source | Pin | Base | What it changes or fixes | How the change is tested |"
        print "|---|---|---|---|---|"
        # our changes first, then the commit pins taken unchanged
        for (pass = 1; pass <= 2; pass++)
            for (i = 1; i <= nlock; i++) {
                name = LOCK[i]
                if (!(name in SEL) || !(name in CH)) continue
                if ((CWHAT[name] ~ /^unchanged/) != (pass == 2)) continue
                base = CBASE[name]; gsub(/\{version\}/, VER[name], base)
                print "| `" name "` | " pin(name) " | " base " | " CWHAT[name] " | " CTEST[name] " |"
            }
    }' "$KIT/sources.lock" "$KIT/pins.notes"
}

# the file with the text between the markers replaced by the tables
rewritten() {
    local file=$1 generated
    if ! grep -q -x -F "$BEGIN" "$file" || ! grep -q -x -F "$END" "$file"; then
        echo "$file: no $BEGIN ... $END markers" >&2
        return 1
    fi
    generated=$(tables)
    awk -v begin="$BEGIN" -v end="$END" -v body="$generated" '
        $0 == begin { print; print body; skip = 1; next }
        $0 == end { skip = 0 }
        !skip' "$file"
}

case "${1:-}" in
--readme)
    new=$(rewritten "$2")
    printf '%s\n' "$new" > "$2"
    ;;
--check)
    if ! diff -u "$2" <(rewritten "$2") > /dev/null; then
        echo "$2: the pins tables are not current; run build/pins-table.sh --readme $2" >&2
        diff -u "$2" <(rewritten "$2") >&2 || true
        exit 1
    fi
    ;;
*)
    tables "$@"
    ;;
esac
